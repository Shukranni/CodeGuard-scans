# Database
# https://docs.djangoproject.com/en/6.0/ref/settings/#databases
#
# Local development uses SQLite.  Free hosting platforms have an *ephemeral*
# filesystem, so a deployed instance MUST point DATABASE_URL at a managed
# Postgres — Neon, Supabase and Aiven all have free tiers that do not expire
# quickly:
#
#   DATABASE_URL=postgresql://user:password@host/dbname?sslmode=require
#
# When DATABASE_URL is absent the project falls back to SQLite, exactly like
# before, so local development is unaffected.

DATABASE_URL = os.environ.get('DATABASE_URL', '').strip()

if DATABASE_URL:
    try:
        import dj_database_url
    except ImportError as exc:  # pragma: no cover - dependency is declared
        raise ImportError(
            'dj-database-url is required when DATABASE_URL is set. '
            'Install it with: pip install dj-database-url'
        ) from exc

    DATABASES = {
        'default': dj_database_url.parse(
            DATABASE_URL,
            conn_max_age=600,
            conn_health_checks=True,
        ),
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


